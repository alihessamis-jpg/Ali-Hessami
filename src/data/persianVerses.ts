// Classical Persian verses (بیت) for the Today page's "بیت روز".
// One beyt per day; picked in round-robin order across poets (see
// lib/dailyVerse.ts) so consecutive days rotate between poets.
// Keys are stable ids — never renumber them, saved rows reference them.

export interface PersianVerse {
  key: string
  poet: string
  line1: string
  line2: string
  source?: string
}

type Raw = [line1: string, line2: string, source?: string]

function poet(prefix: string, name: string, rows: Raw[]): PersianVerse[] {
  return rows.map(([line1, line2, source], i) => ({ key: `${prefix}-${i + 1}`, poet: name, line1, line2, source }))
}

