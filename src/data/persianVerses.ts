// Round-robin interleave so the daily order rotates poets:
// Hafez, Saadi, Rumi, Khayyam, Kashani, Ferdowsi, Nezami, others, Hafez, …
function interleave(groups: PersianVerse[][]): PersianVerse[] {
  const out: PersianVerse[] = []
  const max = Math.max(...groups.map((g) => g.length))
  for (let i = 0; i < max; i++) for (const g of groups) if (g[i]) out.push(g[i])
  return out
}

