## تعامل بیماری کلیوی اولیه (ژنتیکی) و بیماری استخوانی کلیوی

در زیرگروهی از کودکان CKD، بخشی از بیماری استخوانی ناشی از **جهش‌های ژنتیکی اختصاصی** است — مستقل از درجه‌ی نارسایی کلیه و از مکانیسم‌های معمول CKD-MBD. دو گروه اصلی: **سیلیوپاتی‌های اولیه** و **بیماری‌های ذخیره‌ای**.

**ADPKD** (شایع‌ترین نفروپاتی ارثی): در مدل موشی حذف شرطی PKD1/PKD2 در استئوبلاست‌ها، استئوپنی با گردش پایین دیده می‌شود. در بزرگسالان ADPKD: گردش پایین، ALP پایین، **FGF23 بالا** و **هیپوفسفاتمی قابل‌توجه**.

**هیپراگزالوری اولیه** (اتوزومال مغلوب): اثر مستقیم مخرب بر استخوان. استخوان می‌تواند مقادیر عظیمی اگزالات ذخیره کند؛ بیماران با **شکستگی‌های مکرر با ترومای کم، دفورمیتی و درد شدید استخوان** مراجعه می‌کنند. رسوبات اگزالات کلسیم در **فضای مغز استخوان** (نه در ماتریکس) تجمع می‌یابند و با واکنش گرانولوماتوز همراه‌اند. ⚠️ **حتی همودیالیز فشرده اگزالات را به‌اندازه‌ی کافی برنمی‌دارد** و بیماری استخوانی روی دیالیز **بدتر می‌شود**.

**سیستینوز** (بیماری ذخیره‌ای لیزوزومی، اتوزومال مغلوب؛ کمبود سیستینوزین):
۱. اوایل کودکی: توبولوپاتی پروگزیمال کامل با اسیدوز و **هیپوفسفاتمی عمیق (فانکونی)**؛ ۹۵٪ کودکان کوتاهی قد، استئوپنی و راشیتیسم دارند.
۲. اواخر دهه‌ی اول/دهه‌ی دوم: نفریت بینابینی مزمن پیشرونده ← ESKD ← بیماری استخوانی اورمیک ناشی از هیپرپاراتیروئیدی ثانویه.
۳. اثر مستقیم ژنتیکی: کمبود سیستینوزین در سلول‌های استخوانی خود باعث از‌دست‌رفتن استخوان می‌شود، مستقل از نارسایی کلیه.
۴. **سیستئامین** (درمان اصلی) وابسته به دوز روی استخوان اثر می‌کند: **دوز پایین** ← اثر ضدبازجذبی و تحریک تمایز استئوبلاستی و مینرالیزاسیون؛ **دوز بالا** ← مهار تمایز استئوبلاست.

**سایر سندرم‌های ژنتیکی:** جهش‌های NPHP6، MKS1 یا MKS3 (نفرونوفتیز/سیلیوپاتی) ممکن است پاتولوژی استخوانی مستقل از نارسایی کلیه ایجاد کنند. بیماری اسکلتی در **سندرم Pierson** ممکن است با فقدان لامینین-β2 در استخوان تشدید شود.

> **نکته‌ی امتحانی:** اگر بیمار CKD با بیماری استخوانی نامتناسب با شدت نارسایی کلیه مراجعه کرد، به بیماری زمینه‌ای ژنتیکی (به‌ویژه ADPKD، هیپراگزالوری اولیه یا سیستینوز) فکر کنید.

